import { PostgreSqlContainer, type StartedPostgreSqlContainer } from '@testcontainers/postgresql';
import { sql } from 'drizzle-orm';
import type { Pool } from 'pg';
import request from 'supertest';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { createApp } from '../src/app.js';
import { createDb, createPool } from '../src/db/index.js';
import { migrate } from '../src/migrate.js';

// Application complète sur un PostgreSQL 16 jetable (migrations comprises).
// make test-integration ; Docker requis.
async function demarrer(): Promise<{ postgres: StartedPostgreSqlContainer; pool: Pool }> {
  const postgres = await new PostgreSqlContainer('postgres:16').start();
  return { postgres, pool: createPool(postgres.getConnectionUri()) };
}

async function migrationsAppliquees(pool: Pool): Promise<number> {
  const { rows } = await pool.query('select count(*) as n from drizzle.__drizzle_migrations');
  return Number(rows[0].n);
}

describe('backend (e2e)', () => {
  let postgres: StartedPostgreSqlContainer;
  let pool: Pool;

  beforeAll(async () => {
    ({ postgres, pool } = await demarrer());
    await migrate(pool);
  });

  afterAll(async () => {
    await pool?.end();
    await postgres?.stop();
  });

  it('GET /health : ok avec une vraie base', async () => {
    const db = createDb(pool);
    const res = await request(createApp(() => db.execute(sql`select 1`)))
      .get('/health')
      .expect(200);
    expect(res.body).toEqual({ status: 'ok' });
  });

  it('migrations appliquées une seule fois, rejouables sans effet', async () => {
    const avant = await migrationsAppliquees(pool);
    expect(avant).toBeGreaterThan(0);
    await Promise.all([migrate(pool), migrate(pool)]); // deux réplicas en même temps
    expect(await migrationsAppliquees(pool)).toBe(avant);
  });
});

// Base existante de l'ancien backend Spring (dev, qualif) : tables item et Flyway
describe('reprise d’une base existante (e2e)', () => {
  let postgres: StartedPostgreSqlContainer;
  let pool: Pool;

  beforeAll(async () => {
    ({ postgres, pool } = await demarrer());
    await pool.query(`
      create table flyway_schema_history (script varchar(1000) not null, success boolean not null);
      insert into flyway_schema_history values ('V1__init.sql', true), ('V2__item.sql', true);
      create table item (id bigint generated by default as identity primary key, nom varchar(200) not null);
      insert into item (nom) values ('existant');
    `);
  });

  afterAll(async () => {
    await pool?.end();
    await postgres?.stop();
  });

  it('démarre sans erreur et ne touche pas aux tables existantes', async () => {
    await migrate(pool);
    expect(await migrationsAppliquees(pool)).toBeGreaterThan(0);
    const { rows } = await pool.query('select nom from item');
    expect(rows).toEqual([{ nom: 'existant' }]);
  });
});
