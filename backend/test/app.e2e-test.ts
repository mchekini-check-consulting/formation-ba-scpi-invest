import { PostgreSqlContainer, type StartedPostgreSqlContainer } from '@testcontainers/postgresql';
import type { Pool } from 'pg';
import request from 'supertest';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { createApp } from '../src/app.js';
import { createPool } from '../src/db.js';
import { migrate } from '../src/migrate.js';

// Application complète sur un PostgreSQL 16 jetable (migrations comprises).
// make test-integration ; Docker requis.
describe('backend (e2e)', () => {
  let postgres: StartedPostgreSqlContainer;
  let pool: Pool;

  beforeAll(async () => {
    postgres = await new PostgreSqlContainer('postgres:16').start();
    pool = createPool(postgres.getConnectionUri());
    await migrate(pool);
  });

  afterAll(async () => {
    await pool?.end();
    await postgres?.stop();
  });

  it('crée puis liste un item', async () => {
    const app = createApp(pool);
    const cree = await request(app).post('/items').send({ nom: 'Premier' }).expect(201);
    expect(cree.body).toMatchObject({ id: 1, nom: 'Premier', description: null });
    const liste = await request(app).get('/items').expect(200);
    expect(liste.body).toHaveLength(1);
  });

  it('migrations rejouables sans effet', async () => {
    await migrate(pool);
  });
});

// Base déjà migrée par Flyway (ancien backend Spring, environnements existants)
describe('reprise d’une base Flyway (e2e)', () => {
  let postgres: StartedPostgreSqlContainer;
  let pool: Pool;

  beforeAll(async () => {
    postgres = await new PostgreSqlContainer('postgres:16').start();
    pool = createPool(postgres.getConnectionUri());
    await pool.query(`
      create table flyway_schema_history (script varchar(1000) not null, success boolean not null);
      insert into flyway_schema_history values ('V1__init.sql', true), ('V2__item.sql', true);
      create table item (
        id bigint generated by default as identity primary key,
        nom varchar(200) not null,
        description varchar(1000),
        cree_le timestamp with time zone not null default now()
      );
      insert into item (nom) values ('existant');
    `);
  });

  afterAll(async () => {
    await pool?.end();
    await postgres?.stop();
  });

  it('ne rejoue pas V1/V2 et garde les données', async () => {
    await migrate(pool);
    const { rows } = await pool.query('select nom from schema_migrations order by nom');
    expect(rows.map((r) => r.nom)).toEqual(['V1__init.sql', 'V2__item.sql']);
    const liste = await request(createApp(pool)).get('/items').expect(200);
    expect(liste.body).toMatchObject([{ nom: 'existant' }]);
  });
});
